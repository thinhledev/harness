// The single source every emitter builds on: skills/<name>/SKILL.md and
// agents/<name>.md, each a frontmatter block plus a markdown body.

import fs from 'node:fs';
import path from 'node:path';

export const GENERATED_MARK = 'generated by @thinhledev/harness';

export function readSkills(pkgRoot) {
  const dir = path.join(pkgRoot, 'skills');
  return fs.readdirSync(dir).sort()
    .filter((name) => fs.existsSync(path.join(dir, name, 'SKILL.md')))
    .map((name) => {
      const from = `skills/${name}/SKILL.md`;
      return { name, from, raw: fs.readFileSync(path.join(pkgRoot, from), 'utf8') };
    });
}

export function readAgents(pkgRoot) {
  const dir = path.join(pkgRoot, 'agents');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((file) => {
    const from = `agents/${file}`;
    const raw = fs.readFileSync(path.join(pkgRoot, from), 'utf8');
    const { fields, body } = parseFrontmatter(raw);
    return { name: fields.name ?? path.basename(file, '.md'), from, raw, fields, body };
  });
}

/** Flat `key: value` frontmatter — all the source files use. */
export function parseFrontmatter(raw) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return { fields: {}, body: raw };
  const fields = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (kv) fields[kv[1]] = kv[2].trim();
  }
  return { fields, body: raw.slice(m[0].length).replace(/^\n+/, '') };
}

export function markText(version, from) {
  return `${GENERATED_MARK} ${version} from ${from}. Rerun \`harness init\` to update; local edits are overwritten.`;
}

/** Adds the ownership mark right after markdown frontmatter, which must stay first. */
export function stampMarkdown(content, from, version) {
  const mark = `<!-- ${markText(version, from)} -->`;
  const frontmatter = content.match(/^---\n[\s\S]*?\n---\n/);
  if (!frontmatter) return `${mark}\n\n${content}`;
  return `${frontmatter[0]}${mark}\n${content.slice(frontmatter[0].length)}`;
}

export function isOwned(content) {
  return content.includes(GENERATED_MARK);
}
