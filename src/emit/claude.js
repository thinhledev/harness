// Claude Code emitter: skills become .claude/skills/<name>/SKILL.md (auto-
// triggered by description), agents become .claude/agents/<name>.md.

import fs from 'node:fs';
import path from 'node:path';

export const GENERATED_MARK = 'generated by @thinhledev/harness';

export function planClaudeFiles(pkgRoot, version) {
  const files = [];
  const skillsDir = path.join(pkgRoot, 'skills');
  for (const name of fs.readdirSync(skillsDir).sort()) {
    const source = path.join(skillsDir, name, 'SKILL.md');
    if (!fs.existsSync(source)) continue;
    files.push({
      dest: `.claude/skills/${name}/SKILL.md`,
      content: stamp(fs.readFileSync(source, 'utf8'), `skills/${name}/SKILL.md`, version),
    });
  }
  const agentsDir = path.join(pkgRoot, 'agents');
  for (const file of fs.readdirSync(agentsDir).filter((f) => f.endsWith('.md')).sort()) {
    files.push({
      dest: `.claude/agents/${file}`,
      content: stamp(fs.readFileSync(path.join(agentsDir, file), 'utf8'), `agents/${file}`, version),
    });
  }
  return files;
}

/** Adds the ownership mark right after the frontmatter, which must stay first. */
export function stamp(content, from, version) {
  const mark = `<!-- ${GENERATED_MARK} ${version} from ${from}. Rerun \`harness init\` to update; local edits are overwritten. -->`;
  const frontmatter = content.match(/^---\n[\s\S]*?\n---\n/);
  if (!frontmatter) return `${mark}\n\n${content}`;
  return `${frontmatter[0]}${mark}\n${content.slice(frontmatter[0].length)}`;
}

export function isOwned(content) {
  return content.includes(GENERATED_MARK);
}
