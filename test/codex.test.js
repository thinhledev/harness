import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { pkgRoot } from './helpers.js';
import { planCodexFiles, agentToml } from '../src/emit/codex.js';
import { readAgents } from '../src/emit/source.js';
import { detectTargets, parseTargets } from '../src/emit/index.js';
import { makeProject } from './helpers.js';

// A TOML parser for checking the emitted files: python's tomllib (3.11+), when present.
const python = ['python3.14', 'python3.13', 'python3.12', 'python3.11', 'python3']
  .find((bin) => spawnSync(bin, ['-c', 'import tomllib'], { encoding: 'utf8' }).status === 0);

function parseToml(text) {
  const result = spawnSync(python, ['-c', 'import sys, json, tomllib; print(json.dumps(tomllib.loads(sys.stdin.read())))'], { input: text, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  return JSON.parse(result.stdout);
}

test('skills go to .agents/skills unchanged apart from the mark', () => {
  const files = planCodexFiles(pkgRoot, '0.1.0');
  const skill = files.find((f) => f.dest === '.agents/skills/harness-verify/SKILL.md');
  assert.ok(skill.content.startsWith('---\nname: harness-verify\ndescription: '));
  assert.match(skill.content, /generated by @thinhledev\/harness 0\.1\.0/);
});

test('agent TOML carries the required fields and parses back to the source', { skip: !python && 'no python with tomllib' }, () => {
  for (const agent of readAgents(pkgRoot)) {
    const parsed = parseToml(agentToml(agent, '0.1.0'));
    assert.equal(parsed.name, agent.name);
    assert.equal(parsed.description, agent.fields.description);
    assert.equal(parsed.developer_instructions, agent.body.endsWith('\n') ? agent.body : `${agent.body}\n`);
    assert.equal(parsed.sandbox_mode, agent.name === 'reviewer' ? 'read-only' : undefined, agent.name);
    assert.equal(parsed.tools, undefined, 'Claude tool lists are not carried over');
  }
});

test('TOML strings survive quotes, backslashes and triple quotes', { skip: !python && 'no python with tomllib' }, () => {
  const agent = {
    name: 'odd',
    from: 'agents/odd.md',
    fields: { description: 'Say "hi" \\ bye\ttab' },
    body: "Literal ''' breaks literal strings.\nBackslash \\n stays, \"\"\" too.\n",
  };
  const parsed = parseToml(agentToml(agent, '0.1.0'));
  assert.equal(parsed.description, agent.fields.description);
  assert.equal(parsed.developer_instructions, agent.body);
});

test('detectTargets and parseTargets', () => {
  assert.deepEqual(detectTargets(makeProject({})).targets, ['claude', 'codex']);
  assert.deepEqual(detectTargets(makeProject({ '.agents/skills/x/': '' })).targets, ['codex']);
  assert.deepEqual(detectTargets(makeProject({ 'CLAUDE.md/': '' })).targets, ['claude', 'codex'], 'a directory named CLAUDE.md is not a signal');
  assert.deepEqual(parseTargets(['codex,claude']), { targets: ['claude', 'codex'] });
  assert.deepEqual(parseTargets(['all']), { targets: ['claude', 'codex'] });
  assert.match(parseTargets(['cursor']).error, /Unknown agent: cursor/);
});
