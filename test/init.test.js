import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { makeProject, read, scriptedIo, pkgRoot } from './helpers.js';
import { init, mergeFacts } from '../src/init.js';
import { parseSection } from '../src/context.js';

const run = (root, options = {}, answers = []) => {
  const io = scriptedIo(answers);
  return init({ root, pkgRoot, version: '0.1.0', interactive: false, io, ...options }).then((r) => ({ ...r, io }));
};

test('with no agent configuration, writes for both Claude Code and Codex', async () => {
  const root = makeProject({ 'package.json': { scripts: { test: 'node --test' } } });
  const { results, targets, io } = await run(root);

  assert.deepEqual(targets, ['claude', 'codex']);
  assert.equal(io.lines[1], 'Agents: Claude Code, Codex (no agent configuration found, so both)');
  const written = results.filter((r) => r.status === 'created').map((r) => r.dest).sort();
  assert.deepEqual(written, [
    '.agents/skills/harness-review/SKILL.md', '.agents/skills/harness-tech-design/SKILL.md',
    '.agents/skills/harness-ui-design/SKILL.md', '.agents/skills/harness-verify/SKILL.md',
    '.agents/skills/harness-write/SKILL.md',
    '.claude/agents/architect.md', '.claude/agents/builder.md', '.claude/agents/designer.md',
    '.claude/agents/reviewer.md', '.claude/agents/verifier.md',
    '.claude/skills/harness-review/SKILL.md', '.claude/skills/harness-tech-design/SKILL.md',
    '.claude/skills/harness-ui-design/SKILL.md', '.claude/skills/harness-verify/SKILL.md',
    '.claude/skills/harness-write/SKILL.md',
    '.codex/agents/architect.toml', '.codex/agents/builder.toml', '.codex/agents/designer.toml',
    '.codex/agents/reviewer.toml', '.codex/agents/verifier.toml',
    'AGENTS.md', 'CLAUDE.md',
  ]);
  assert.equal(read(root, 'CLAUDE.md'), '@AGENTS.md\n');
  assert.equal(parseSection(read(root, 'AGENTS.md')).facts.unit.value, 'npm test');

  const skill = read(root, '.claude/skills/harness-verify/SKILL.md');
  assert.ok(skill.startsWith('---\nname: harness-verify\n'), 'frontmatter stays first');
  assert.match(skill, /generated by @thinhledev\/harness 0\.1\.0/);
});

test('rerun is idempotent', async () => {
  const root = makeProject({ 'go.mod': 'module x' });
  await run(root);
  const { results } = await run(root);
  assert.ok(results.every((r) => r.status === 'unchanged'), JSON.stringify(results));
});

test('interactive: guardrails are added and facts corrected before writing', async () => {
  const root = makeProject({ 'go.mod': 'module x' });
  const answers = ['run the deploy script', "Don't touch the prod database", '', '2 n/a', '9 nope', '3 docs/brand.md', ''];
  const { facts, guardrails, io } = await run(root, { interactive: true }, answers);

  assert.deepEqual(guardrails, ['Never run the deploy script', "Don't touch the prod database"]);
  assert.equal(facts.e2e.value, 'not applicable');
  assert.deepEqual(facts.design, { value: 'docs/brand.md', source: 'confirmed at init' });
  assert.ok(io.lines.some((l) => l.includes('Expected a number from 1 to 5')));

  const recorded = parseSection(read(root, 'AGENTS.md'));
  assert.equal(recorded.facts.e2e.value, 'not applicable');
  assert.deepEqual(recorded.guardrails, guardrails);
});

test('rerun keeps recorded facts and guardrails, notes a differing scan, refills open facts', async () => {
  const root = makeProject({ 'go.mod': 'module x' });
  await run(root, { interactive: true }, ['never deploy on fridays', '', '1 go test -race ./...', '']);

  fs.writeFileSync(path.join(root, 'DESIGN.md'), '# Design');
  const { facts, guardrails, io } = await run(root);

  assert.equal(facts.unit.value, 'go test -race ./...');
  assert.ok(io.lines.some((l) => l.includes('scan now finds go test ./... (go.mod present)')));
  assert.equal(facts.design.value, 'DESIGN.md', 'a fact recorded as none is refilled by the scan');
  assert.deepEqual(guardrails, ['Never deploy on fridays']);
});

test('keeps the rest of an existing AGENTS.md and CLAUDE.md', async () => {
  const root = makeProject({ 'AGENTS.md': '# Rules\n\nUse tabs.\n', 'CLAUDE.md': '# Claude\n\nBe brief.\n' });
  await run(root);
  assert.ok(read(root, 'AGENTS.md').startsWith('# Rules\n\nUse tabs.\n\n<!-- harness:begin -->'));
  assert.equal(read(root, 'CLAUDE.md'), '# Claude\n\nBe brief.\n\n@AGENTS.md\n');
});

test('never overwrites an agent or skill it did not write, unless forced', async () => {
  const root = makeProject({ '.claude/agents/reviewer.md': '---\nname: reviewer\n---\nmine\n' });
  const { results, io } = await run(root);
  assert.equal(results.find((r) => r.dest === '.claude/agents/reviewer.md').status, 'conflict');
  assert.equal(read(root, '.claude/agents/reviewer.md'), '---\nname: reviewer\n---\nmine\n');
  assert.ok(io.lines.some((l) => l.includes('--force')));

  const forced = await run(root, { force: true });
  assert.equal(forced.results.find((r) => r.dest === '.claude/agents/reviewer.md').status, 'updated');
});

test('dry run writes nothing', async () => {
  const root = makeProject({});
  const { results } = await run(root, { dryRun: true });
  assert.ok(results.some((r) => r.status === 'created'));
  assert.deepEqual(fs.readdirSync(root), []);
});

test('mergeFacts: not applicable is a decision, not an open fact', () => {
  const merged = mergeFacts(
    { e2e: { value: 'not applicable', source: 'confirmed at init' } },
    {
      unit: { value: 'x', source: 's' }, e2e: { value: 'y', source: 's' }, design: { value: 'none', source: 's' },
      areas: { value: 'whole repository', source: 's' }, records: { value: 'docs/harness/', source: 'default' },
    },
  );
  assert.equal(merged.e2e.value, 'not applicable');
  assert.match(merged.e2e.note, /scan now finds y/);
});

test('a project that already uses one agent gets only that one', async () => {
  const codexOnly = makeProject({ '.codex/config.toml': '' });
  const codex = await run(codexOnly);
  assert.deepEqual(codex.targets, ['codex']);
  assert.ok(!fs.existsSync(path.join(codexOnly, 'CLAUDE.md')), 'no Claude bridge for a Codex-only project');
  assert.ok(!fs.existsSync(path.join(codexOnly, '.claude')));
  assert.ok(fs.existsSync(path.join(codexOnly, '.codex/agents/verifier.toml')));

  const claudeOnly = makeProject({ 'CLAUDE.md': '# notes\n' });
  const claude = await run(claudeOnly);
  assert.deepEqual(claude.targets, ['claude']);
  assert.equal(claude.io.lines[1], 'Agents: Claude Code (found CLAUDE.md)');
  assert.ok(!fs.existsSync(path.join(claudeOnly, '.agents')));

  const both = makeProject({ '.claude/': '', '.agents/': '' });
  assert.deepEqual((await run(both)).targets, ['claude', 'codex']);
});

test('an explicit target list overrides detection', async () => {
  const root = makeProject({ 'CLAUDE.md': '# notes\n' });
  const { targets, results } = await run(root, { targets: ['codex'] });
  assert.deepEqual(targets, ['codex']);
  assert.ok(!results.some((r) => r.dest === 'CLAUDE.md'));
});

test('warns when the Harness section falls past what Codex reads', async () => {
  const root = makeProject({ 'AGENTS.md': `# Big\n\n${'x'.repeat(40 * 1024)}\n` });
  const codex = await run(root, { targets: ['codex'] });
  assert.ok(codex.io.lines.some((l) => l.includes('Codex reads only the first 32768 bytes')));

  const small = await run(makeProject({}), { targets: ['codex'] });
  assert.ok(!small.io.lines.some((l) => l.includes('Codex reads only')));
});
